"""Transcript PDF generation (ReportLab Platypus).

Unofficial transcripts are always labelled as such (blueprint SS2/SS4);
an official transcript requires registrar issuance first.
"""
import io
from decimal import Decimal

from django.http import HttpResponse
from django.utils import timezone


def build_transcript_pdf(student, *, official: bool = False) -> HttpResponse:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
    )
    from reportlab.lib import colors
    from reportlab.lib.styles import getSampleStyleSheet

    from .services import active_policy, compute_gpa, student_results

    policy = active_policy(student)
    registrations = student_results(student, published_only=True)

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4,
                            topMargin=15 * mm, bottomMargin=15 * mm,
                            leftMargin=15 * mm, rightMargin=15 * mm)
    styles = getSampleStyleSheet()
    story = []
    story.append(Paragraph("University School Management System", styles["Title"]))
    story.append(Paragraph(
        "OFFICIAL TRANSCRIPT" if official else "DRAFT - UNOFFICIAL TRANSCRIPT",
        styles["Heading2"]))
    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph(f"Student: {student.full_name}", styles["Normal"]))
    story.append(Paragraph(f"Matricule: {student.matricule or '-'}", styles["Normal"]))
    if student.program_id:
        story.append(Paragraph(f"Program: {student.program.name}", styles["Normal"]))
    if student.current_level_id:
        story.append(Paragraph(f"Current level: {student.current_level.label}",
                               styles["Normal"]))
    story.append(Paragraph(f"Issued: {timezone.now():%Y-%m-%d}", styles["Normal"]))
    story.append(Spacer(1, 4 * mm))

    by_semester: dict[str, list] = {}
    for reg in registrations:
        label = str(reg.offering.semester) if reg.offering.semester_id else "Other"
        by_semester.setdefault(label, []).append(reg)

    cgpa_rows = []
    for label, regs in by_semester.items():
        story.append(Paragraph(label, styles["Heading3"]))
        data = [["Code", "Course", "Credits", "CA", "Exam", "Total", "Grade", "GP"]]
        semester_rows = []
        total_credits = 0
        for reg in regs:
            r = reg.result
            course = reg.offering.course
            total_credits += course.credits
            semester_rows.append((r, course.credits))
            cgpa_rows.append((r, course.credits))
            data.append([
                course.code, Paragraph(course.title, styles["Normal"]),
                str(course.credits),
                str(r.ca_mark) if r.ca_mark is not None else "-",
                str(r.final_mark) if r.final_mark is not None else "-",
                str(r.total) if r.total is not None else "-",
                r.grade_band.letter if r.grade_band_id else "-",
                str(r.grade_points) if r.grade_points is not None else "-",
            ])
        table = Table(data, colWidths=[22 * mm, 62 * mm, 16 * mm, 14 * mm,
                                       14 * mm, 16 * mm, 16 * mm, 14 * mm])
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        story.append(table)
        gpa = compute_gpa(semester_rows, policy) if policy else None
        story.append(Paragraph(
            f"Semester credits: {total_credits} &nbsp; GPA: {gpa if gpa is not None else '-'}",
            styles["Normal"]))
        story.append(Spacer(1, 3 * mm))

    cgpa = compute_gpa(cgpa_rows, policy) if policy else None
    story.append(Paragraph(f"<b>CGPA: {cgpa if cgpa is not None else '-'}</b>",
                           styles["Normal"]))
    story.append(Spacer(1, 6 * mm))
    story.append(Paragraph(
        "Generated by the School Management System. "
        + ("Official document." if official
           else "Unofficial draft - not valid for official purposes."),
        styles["Italic"]))

    doc.build(story)
    response = HttpResponse(buffer.getvalue(), content_type="application/pdf")
    response["Content-Disposition"] = (
        f'attachment; filename="transcript-{student.matricule or student.id}.pdf"')
    return response
